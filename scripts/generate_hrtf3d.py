#!/usr/bin/env python3
"""Generate NativeDSP/TimbreHRTF3D.h from the mit-hrtf-lib KEMAR compact tables.

The source headers are read as plain text data; nothing from mit-hrtf-lib is
compiled or executed. Usage:

    python3 -I scripts/generate_hrtf3d.py /path/to/mit-hrtf-lib/source NativeDSP/TimbreHRTF3D.h

Data: MIT KEMAR (Bill Gardner and Keith Martin, MIT Media Lab), via
mit-hrtf-lib by Aristotel Digenis (MIT licence). Right-hemisphere positions only
(azimuth 0..180); the renderer mirrors the left side by swapping ears.
"""
import re
import sys
from pathlib import Path

RATES = (44100, 48000, 88200, 96000)
SETS = ('diffuse', 'normal')          # index 0 = diffused, 1 = normal (matches SpatialParams.hrtf)
RINGS = list(range(-40, 91, 10))      # 14 measured elevation rings


def parse(path):
    """{(elevation, azimuth): (left[], right[])} from one mit-hrtf-lib table header."""
    text = Path(path).read_text(encoding='latin-1')
    out = {}
    pattern = r'//\s*H(-?\d+)e(\d+)a\.wav\s*\n\s*\{([^{}]*)\}\s*,\s*\{([^{}]*)\}'
    for m in re.finditer(pattern, text):
        key = (int(m.group(1)), int(m.group(2)))
        left = [int(x) for x in m.group(3).split(',') if x.strip()]
        right = [int(x) for x in m.group(4).split(',') if x.strip()]
        out[key] = (left, right)
    return out


def main(source, output):
    source = Path(source)
    tables = {(s, r): parse(source / s / f'mit_hrtf_{s}_{r}.h') for s in SETS for r in RATES}
    positions = sorted(tables[('normal', 44100)], key=lambda k: (k[0], k[1]))
    for key, table in tables.items():
        if sorted(table) != positions:
            raise SystemExit(f'{key}: position grid differs from the reference set')
    if [e for e in RINGS if not any(p[0] == e for p in positions)]:
        raise SystemExit('missing elevation ring')
    taps = []
    for r in RATES:
        lengths = {len(v[0]) for v in tables[('normal', r)].values()} | \
                  {len(v[1]) for v in tables[('normal', r)].values()}
        if len(lengths) != 1:
            raise SystemExit(f'{r}: inconsistent tap counts {lengths}')
        taps.append(lengths.pop())

    # Nearest measured azimuth for every whole degree 0..180 on each ring.
    index = {p: i for i, p in enumerate(positions)}
    ring_map = []
    for e in RINGS:
        ring = [p for p in positions if p[0] == e]
        ring_map.append([index[min(ring, key=lambda p: (abs(p[1] - a), p[1]))] for a in range(181)])

    lines = [
        '// Generated by scripts/generate_hrtf3d.py. Do not edit.',
        '// MIT KEMAR compact set (Bill Gardner and Keith Martin, MIT Media Lab) via mit-hrtf-lib',
        '// (Aristotel Digenis, MIT licence). Right hemisphere only; mirror the left side by swapping ears.',
        '#pragma once',
        'namespace timbre { namespace hrtf3d {',
        'constexpr unsigned kRates[4] = {%s};' % ', '.join(map(str, RATES)),
        'constexpr unsigned kTaps[4] = {%s};' % ', '.join(map(str, taps)),
        f'constexpr unsigned kMaxTaps = {max(taps)};',
        f'constexpr int kPositions = {len(positions)};',
        f'constexpr int kRings = {len(RINGS)}, kRingFirst = {RINGS[0]}, kRingStep = 10;',
        'constexpr float kScale = 1.0f / 32768.0f;',
        '// Measured azimuth (degrees) of each position; 0 and 180 are on the median plane.',
        'const short kAzimuth[kPositions] = {%s};' % ','.join(str(p[1]) for p in positions),
        'const short kElevation[kPositions] = {%s};' % ','.join(str(p[0]) for p in positions),
        '// [ring][whole degrees of |azimuth| 0..180] -> nearest measured position.',
        'const unsigned short kMap[kRings][181] = {',
    ]
    lines += ['{%s},' % ','.join(map(str, row)) for row in ring_map]
    lines.append('};')
    for ri, r in enumerate(RATES):
        lines.append(f'// [set 0=diffused 1=normal][position][ear 0=right 1=left][tap], int16 at {r} Hz')
        lines.append(f'const short kData{ri}[2][kPositions][2][{taps[ri]}] = {{')
        for s in SETS:
            lines.append('{')
            for p in positions:
                left, right = tables[(s, r)][p]
                lines.append('{{%s},{%s}},' % (','.join(map(str, right)), ','.join(map(str, left))))
            lines.append('},')
        lines.append('};')
    lines.append('}}')
    Path(output).write_text('\n'.join(lines) + '\n')
    print(f'{len(positions)} positions, taps {taps}, wrote {output}')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
